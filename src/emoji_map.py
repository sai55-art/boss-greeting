def to_emoji(text: str) -> str:
    """把 [xxx] 形式的微信表情代码替换为 emoji；未知代码原样保留。"""
    if not text:
        return text
    out = []
    i = 0
    n = len(text)
    while i < n:
        if text[i] == "[":
            j = text.find("]", i + 1)
            if j != -1:
                code = text[i + 1:j]
                if code in EMOJI_MAP:
                    out.append(EMOJI_MAP[code])
                    i = j + 1
                    continue
                # 兼容大小写（[OK]）
                low = code.lower()
                if low in EMOJI_MAP:
                    out.append(EMOJI_MAP[low])
                    i = j + 1
                    continue
        out.append(text[i])
        i += 1
    return "".join(out)